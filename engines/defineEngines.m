function value = localNumber(rawValue)
if ismissing(rawValue)
    value = NaN;
    return;
end

if isnumeric(rawValue)
    value = double(rawValue);
    return;
end

textValue = erase(strtrim(string(rawValue)), ",");
if textValue == ""
    value = NaN;
else
    value = str2double(textValue);
end
end

function angularSpeed_rad_s = localRpmToRadPerSec(rawRpm)
angularSpeed_rad_s = localNumber(rawRpm) * 2 * pi / 60;
end

function temperature_K = localCelsiusToKelvin(rawTemperature_C)
temperature_C = localNumber(rawTemperature_C);
if isnan(temperature_C)
    temperature_K = NaN;
else
    temperature_K = temperature_C + 273.15;
end
end
